export function createDemoEvidenceInput(category: ProductionEvidenceCategory): ProductionConfigEvidenceInput {
  const base = {
    category,
    environment: 'PRODUCTION' as const,
    evidenceType: 'attestation',
    description: `${getProductionEvidenceRequirement(category).label} evidence for production readiness.`,
    source: 'operator',
    providedBy: 'platform',
  };
  if (category === 'backend_endpoint' || category === 'production_endpoint_reachability') {
    return { ...base, rawValue: 'https://api.uikigai.example.com' };
  }
  if (category === 'database_config') {
    return { ...base, rawValue: 'postgres://prod-user:prod-password@db.example.com/growthos', metadata: { provider: 'postgres' } };
  }
  if (category === 'auth_config') {
    return {
      ...base,
      rawValue: 'auth0-production-config',
      metadata: { provider: 'auth0', issuer: 'https://issuer.example.com', audience: 'growthos', tokenMode: 'jwt', sessionMode: 'cookie' },
    };
  }
  if (category === 'secret_presence') {
    return { ...base, rawValue: 'secret-exists-in-vault', metadata: { presenceConfirmed: true } };
  }
  return { ...base, rawValue: `${category}-proof` };
}

export function addNextMissingDemoEvidence(): ProductionConfigEvidence {
  const dashboard = selectProductionConfigEvidenceDashboard();
  const category = dashboard.missing[0]?.category ?? PRODUCTION_EVIDENCE_CATEGORIES[0];
  return addEvidence(createDemoEvidenceInput(category));
}

export function verifyFirstProvidedEvidence(): ProductionConfigEvidence | undefined {
  const evidence = readState().evidence.find((entry) => entry.status === 'provided');
  return evidence ? verifyEvidence(evidence.id, 'operator_review') : undefined;
}

export function rejectFirstReviewableEvidence(): ProductionConfigEvidence | undefined {
  const evidence = readState().evidence.find((entry) => entry.status === 'provided' || entry.status === 'verified');
  return evidence ? rejectEvidence(evidence.id) : undefined;
}

export function expireFirstVerifiedEvidence(): ProductionConfigEvidence | undefined {
  const evidence = readState().evidence.find((entry) => entry.status === 'verified');
  return evidence ? expireEvidence(evidence.id) : undefined;
}

