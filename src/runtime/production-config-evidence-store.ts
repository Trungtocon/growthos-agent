const PRODUCTION_CONFIG_EVIDENCE_KEY = 'uikigai-production-config-evidence-v1';

export interface ProductionConfigEvidenceState {
  evidence: ProductionConfigEvidence[];
  artifacts: ArtifactRecord[];
  updatedAt: string;
}

function nowIso(): string {
  return new Date().toISOString();
}

function unique(prefix: string): string {
  return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}

function clone<T>(value: T): T {
  return JSON.parse(JSON.stringify(value)) as T;
}

function emptyState(): ProductionConfigEvidenceState {
  return { evidence: [], artifacts: [], updatedAt: nowIso() };
}

function readState(): ProductionConfigEvidenceState {
  if (typeof window === 'undefined') return emptyState();
  try {
    const raw = window.sessionStorage.getItem(PRODUCTION_CONFIG_EVIDENCE_KEY);
    if (!raw) return emptyState();
    const parsed = JSON.parse(raw) as Partial<ProductionConfigEvidenceState>;
    return {
      evidence: parsed.evidence ?? [],
      artifacts: parsed.artifacts ?? [],
      updatedAt: parsed.updatedAt ?? nowIso(),
    };
  } catch {
    return emptyState();
  }
}

function writeState(state: ProductionConfigEvidenceState) {
  if (typeof window === 'undefined') return;
  window.sessionStorage.setItem(PRODUCTION_CONFIG_EVIDENCE_KEY, JSON.stringify({ ...state, updatedAt: nowIso() }));
}

function patchEvidence(id: string, patch: Partial<ProductionConfigEvidence>): ProductionConfigEvidence | undefined {
  const state = readState();
  const evidence = state.evidence.map((entry) => entry.id === id ? { ...entry, ...patch } : entry);
  const updated = evidence.find((entry) => entry.id === id);
  writeState({ ...state, evidence });
  return updated ? clone(updated) : undefined;
}

function exportedArtifact(name: string, type: ArtifactRecord['type'], content: unknown): ArtifactRecord {
  const createdAt = nowIso();
  return registerArtifact({
    id: `artifact-production-config-evidence-${name.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}`,
    name,
    type,
    lifecycle: 'AVAILABLE',
    workspaceId: demoWorkspace.id,
    version: 1,
    metadata: {
      workspaceId: demoWorkspace.id,
      source: 'mock',
      sourceType: 'production-config-evidence',
      contentSummary: `${name} generated by production config evidence binder. Raw secret values are excluded.`,
      tags: ['production-config-evidence', 'go-live', 'redacted'],
      sizeBytes: JSON.stringify(content).length,
    },
    createdAt,
    updatedAt: createdAt,
  });
}

export function getProductionConfigEvidenceState(): ProductionConfigEvidenceState {
  return clone(readState());
}

export function addEvidence(input: ProductionConfigEvidenceInput): ProductionConfigEvidence {
  const sanitized = sanitizeProductionEvidenceInput(input);
  const record: ProductionConfigEvidence = {
    id: unique(`production-evidence-${input.category}`),
    providedAt: nowIso(),
    ...sanitized,
  };
  const state = readState();
  writeState({ ...state, evidence: [record, ...state.evidence].slice(0, 80) });
  return clone(record);
}

export function verifyEvidence(id: string, verificationMethod = 'manual_review'): ProductionConfigEvidence | undefined {
  const state = readState();
  const evidence = state.evidence.find((entry) => entry.id === id);
  if (!evidence) return undefined;
  const warnings = validateProductionEvidenceInput({
    category: evidence.category,
    environment: evidence.environment,
    evidenceType: evidence.evidenceType,
    description: evidence.description,
    source: evidence.source,
    providedBy: evidence.providedBy,
    maskedValue: evidence.maskedValue,
    expiresAt: evidence.expiresAt,
    metadata: evidence.metadata,
  });
  if (warnings.some((warning) => /invalid|unsafe|missing|required/i.test(warning))) {
    return patchEvidence(id, {
      status: 'rejected',
      severity: 'critical',
      warnings: Array.from(new Set([...evidence.warnings, ...warnings])),
      verificationMethod,
      verifiedAt: undefined,
    });
  }
  if (isProductionEvidenceExpired(evidence)) {
    return patchEvidence(id, {
      status: 'expired',
      warnings: Array.from(new Set([...evidence.warnings, 'Evidence expired before verification.'])),
    });
  }
  return patchEvidence(id, {
    status: 'verified',
    verifiedAt: nowIso(),
    verificationMethod,
    warnings,
  });
}

export function rejectEvidence(id: string, reason = 'Evidence rejected by reviewer.'): ProductionConfigEvidence | undefined {
  return patchEvidence(id, {
    status: 'rejected',
    severity: 'critical',
    warnings: [reason],
    verifiedAt: undefined,
  });
}

export function expireEvidence(id: string): ProductionConfigEvidence | undefined {
  return patchEvidence(id, {
    status: 'expired',
    expiresAt: nowIso(),
    warnings: ['Evidence was expired and no longer unlocks production gates.'],
  });
}

export function clearProductionConfigEvidence() {
  if (typeof window === 'undefined') return;
  window.sessionStorage.removeItem(PRODUCTION_CONFIG_EVIDENCE_KEY);
}

