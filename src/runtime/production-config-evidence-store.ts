export function getProductionEvidenceStatusForCategory(category: ProductionEvidenceCategory): ProductionEvidenceStatus {
  const dashboard = selectProductionConfigEvidenceDashboard();
  if (dashboard.verified.some((entry) => entry.category === category)) return 'verified';
  if (dashboard.expired.some((entry) => entry.category === category)) return 'expired';
  if (dashboard.rejected.some((entry) => entry.category === category)) return 'rejected';
  if (dashboard.provided.some((entry) => entry.category === category)) return 'provided';
  return 'missing';
}

export function exportProductionConfigEvidencePack(): ArtifactRecord[] {
  const dashboard = selectProductionConfigEvidenceDashboard();
  const observability = selectObservabilityDashboard();
  const redactedEvidence = dashboard.evidence.map((entry) => ({
    ...entry,
    metadata: entry.metadata ? Object.fromEntries(Object.entries(entry.metadata).map(([key, value]) => [key, typeof value === 'string' && /secret|token|password|key/i.test(key) ? '***redacted***' : value])) : undefined,
  }));
  const artifacts = [
    exportedArtifact('production-config-evidence.json', 'AUDIT', redactedEvidence),
    exportedArtifact('production-config-evidence-summary.md', 'REPORT', dashboard),
    exportedArtifact('production-evidence-blockers.json', 'AUDIT', dashboard.remainingBlockers),
    exportedArtifact('production-evidence-redaction-report.md', 'REPORT', {
      policy: 'Raw secrets are never stored. Values are masked at ingestion and exports contain masked evidence only.',
      evidenceCount: redactedEvidence.length,
    }),
    exportedArtifact('production-go-live-evidence-pack.md', 'REPORT', {
      verdict: dashboard.verdict,
      readinessScore: dashboard.readinessScore,
      resolvedBlockers: dashboard.resolvedBlockers,
      remainingBlockers: dashboard.remainingBlockers,
      observabilityVerdict: observability.verdict,
      observabilityScore: observability.readinessScore,
    }),
    exportedArtifact('production-config-final-verdict.md', 'REPORT', dashboard.verdict),
  ];
  const state = readState();
  writeState({ ...state, artifacts });
  return clone(artifacts);
}

